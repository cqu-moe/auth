import { writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { getEndpoints } from "better-auth/api";
import { createAuth } from "../src/auth";
import type { Env } from "../src/types";

const database = new DatabaseSync(":memory:");
const env = {
  DATABASE: database,
  BETTER_AUTH_URL: "https://auth.cqu.moe",
  BETTER_AUTH_SECRET: "local-generation-secret-not-for-production",
  AUTH_RESEND_API_KEY: "re_local_generation",
} as unknown as Env;

async function main() {
try {
  const auth = createAuth(env, new Request("https://auth.cqu.moe"));
  const { api } = getEndpoints(await auth.$context, auth.options);
  const operations = Object.values(api)
    .filter((endpoint) => endpoint.path && !endpoint.options.metadata?.SERVER_ONLY)
    .filter((endpoint) => !auth.options.disabledPaths?.includes(endpoint.path))
    .flatMap((endpoint) => {
      const methods = Array.isArray(endpoint.options.method)
        ? endpoint.options.method
        : [endpoint.options.method];
      return methods.map((method) => ({ method, path: endpoint.path }));
    })
    .sort((a, b) => `${a.path} ${a.method}`.localeCompare(`${b.path} ${b.method}`));
  const output = [
    "// Generated by scripts/generate-auth-operations.ts. Do not edit by hand.",
    `export const AUTH_OPERATIONS = ${JSON.stringify(operations, null, 2)} as const;`,
    "",
  ].join("\n");
  writeFileSync(new URL("../src/api/auth-operations.generated.ts", import.meta.url), output);
} finally {
  database.close();
}
}

void main();

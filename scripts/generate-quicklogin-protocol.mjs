#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
let extensionRoot = null;
let check = false;
let printDigest = false;
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--check') check = true;
  else if (args[i] === '--print-digest') printDigest = true;
  else if (args[i] === '--extension-root' && args[i + 1]) extensionRoot = resolve(args[++i]);
  else throw new Error(`Unknown or incomplete argument: ${args[i]}`);
}
const source = await readFile(resolve(root, 'src/services/quicklogin/protocol-v3.ts'), 'utf8');
const digest = createHash('sha256').update(source).digest('hex');
const generated = `// Generated by Auth scripts/generate-quicklogin-protocol.mjs. Do not edit.\n${source}\nexport const CONTRACT_DIGEST = '${digest}' as const;\n`;
const targets = [resolve(root, 'frontend/src/lib/api/quicklogin-protocol.generated.ts')];
if (extensionRoot) targets.push(resolve(extensionRoot, 'src/shared/protocol-v3.generated.ts'));
for (const target of targets) {
  if (check) {
    const actual = await readFile(target, 'utf8');
    if (actual !== generated) throw new Error(`QuickLogin protocol drift: ${target}. Regenerate from the canonical Auth contract.`);
  } else {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, generated);
  }
}
console.log(printDigest ? digest : `${check ? 'Verified' : 'Generated'} ${targets.length} QuickLogin v3 consumer(s); sha256=${digest}`);
